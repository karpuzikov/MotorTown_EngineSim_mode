#!/usr/bin/env python3
"""Generate Engine Simulator scripts for the real engines in real_engines.py.

Each output native/profiles/es_<engine>.mr is a self-contained engine:
the real bore, stroke, cylinder count and layout, bank angle, the maker's
firing order and cylinder numbering (which decides which exhaust each pulse
reaches: the V8 burble, the boxer rumble), compression, redline and cam/
intake/exhaust defaults for the car's character. Head flow, runners and
plenum scale from the GM LS model shipped with Engine Simulator.

Usage: make_engines.py [--gains gains.json]   (gains: offline calibration)
"""
import argparse
import json
import math
from pathlib import Path

from real_engines import ENGINES, FALLBACK, VEHICLES

OUT = Path(__file__).resolve().parents[1]
INCH = 25.4

STYLES = {
    #           cam dur@50  lift(in) LSA  timing max  ir                           exhaust vol  idle plate
    "economy": dict(dur=208, lift=0.38, lsa=112, adv=34, ir="mild_exhaust_0", audio=1.0, plate=0.996),
    "sport":   dict(dur=232, lift=0.45, lsa=110, adv=36, ir="mild_exhaust_0_reverb", audio=1.6, plate=0.996),
    "muscle":  dict(dur=228, lift=0.48, lsa=110, adv=36, ir="default_0", audio=4.0, plate=0.996),
    "luxury":  dict(dur=200, lift=0.40, lsa=114, adv=32, ir="mild_exhaust_0", audio=0.8, plate=0.996),
    "vintage": dict(dur=196, lift=0.32, lsa=114, adv=24, ir="default_0", audio=1.6, plate=0.993),
    "truck":   dict(dur=204, lift=0.40, lsa=114, adv=30, ir="default_0", audio=1.6, plate=0.996),
    "bike":    dict(dur=232, lift=0.36, lsa=106, adv=32, ir="minimal_muffling_01", audio=1.0, plate=0.99),
    # Diesels are unthrottled: plenty of air at "closed" throttle.
    "diesel":  dict(dur=200, lift=0.45, lsa=114, adv=14, ir="default_0", audio=2.0, plate=0.93),
}


def banks_for(spec):
    """Bank angle per cylinder number (1-based) and the list of banks."""
    n, layout = spec["cyl"], spec["layout"]
    if layout == "I":
        return {c: 0.0 for c in range(1, n + 1)}, [0.0]
    half = spec["v_angle"] / 2.0 if layout == "V" else 90.0
    a, b = -half, half
    if spec.get("numbering", "gm") == "gm":
        bank = {c: (a if c % 2 == 1 else b) for c in range(1, n + 1)}
    else:  # ford / vw / porsche / lamborghini: first half on one bank
        bank = {c: (a if c <= n // 2 else b) for c in range(1, n + 1)}
    return bank, [a, b]


def fire_times(spec):
    order = spec["firing"]
    times = spec.get("fire_times") or [k * 720.0 / len(order) for k in range(len(order))]
    return {cyl: t for cyl, t in zip(order, times)}


def generate(key, spec, gain):
    n = spec["cyl"]
    style = STYLES[spec["style"]]
    bank_of, banks = banks_for(spec)
    fires = fire_times(spec)
    assert sorted(fires) == list(range(1, n + 1)), key
    ref = banks[0]
    bore, stroke = spec["bore"], spec["stroke"]
    rod = spec.get("rod", round(1.7 * stroke, 1))
    disp_cyl_cc = math.pi / 4 * (bore / 10) ** 2 * (stroke / 10)
    disp_l = disp_cyl_cc * n / 1000
    chamber_cc = disp_cyl_cc / (spec["cr"] - 1)
    redline = spec["redline"]
    scale = spec.get("rpm_scale", 1)
    sim_redline = redline * scale
    # Airflow scaled like the GM LS model (5.7 L, 6500 rpm, k_carb 700).
    cfm = max(40.0, disp_l * 61.02 * sim_redline / 3456 * (1.1 if spec["style"] in ("sport", "bike") else 0.95))
    if spec.get("rpm_scale", 1) > 1:
        cfm /= scale  # same air per real revolution
    per_cyl = disp_cyl_cc / 712.0
    flow_scale = (bore / 96.0) ** 2
    lift_scale = style["lift"] / 0.551
    # Small cylinders need finer steps (Engine Simulator's own bike/ATV
    # models run 20-40 kHz); 10+ cylinders run coarser to stay real-time.
    sim_freq = 40000 if disp_cyl_cc < 250 else 20000 if disp_cyl_cc < 500 else 10000 if n <= 8 else 8000
    crank_mass_lb = max(4.0, 7.5 * disp_l)
    fly_mass_lb = max(3.0, 5 * disp_l ** 0.7)

    L = []
    w = L.append
    if gain is not None:
        w(f"// mtes-output-gain: {gain:.3g}")
    if scale != 1:
        w(f"// mtes-rpm-scale: {scale}")
    w(f"// {spec['name']}: {n} cyl, {disp_l:.2f} L, bore {bore} x stroke {stroke} mm,")
    w(f"// firing order {'-'.join(map(str, spec['firing']))}, redline {redline} rpm. Generated by")
    w("// native/profiles/generator/make_engines.py from real_engines.py.")
    w('import "engine_sim.mr"\n')
    w("units units()\nconstants constants()\nimpulse_response_library ir_lib()\n")

    w("private node wires {")
    for c in range(1, n + 1):
        w(f"    output wire{c}: ignition_wire();")
    w("}\n")

    w("private node head {")
    w("    input intake_camshaft;\n    input exhaust_camshaft;\n    input flip_display: false;")
    w("    alias output __out: head;")
    for kind, table in (("intake", [0, 1, 103, 156, 214, 249, 268, 280, 280, 281]),
                        ("exhaust", [0, 1, 72, 113, 160, 196, 222, 235, 245, 246])):
        w(f"    function {kind}_flow(50 * units.thou * {lift_scale:.4f})")
        w(f"    {kind}_flow")
        for i, f in enumerate(table):
            w(f"        .add_flow_sample({i * 50} * {lift_scale:.4f}, {f} * {flow_scale:.4f})")
    w("    generic_cylinder_head head(")
    w(f"        chamber_volume: {chamber_cc:.2f} * units.cc,")
    w(f"        intake_runner_volume: {149.6 * per_cyl:.2f} * units.cc,")
    w(f"        intake_runner_cross_section_area: {(2.2 * math.sqrt(per_cyl)) ** 2:.3f} * units.inch * units.inch,")
    w(f"        exhaust_runner_volume: {50.0 * per_cyl:.2f} * units.cc,")
    w(f"        exhaust_runner_cross_section_area: {(1.75 * math.sqrt(per_cyl)) ** 2:.3f} * units.inch * units.inch,")
    w("        intake_port_flow: intake_flow,\n        exhaust_port_flow: exhaust_flow,")
    w("        valvetrain: standard_valvetrain(intake_camshaft: intake_camshaft, exhaust_camshaft: exhaust_camshaft),")
    w("        flip_display: flip_display\n    )\n}\n")

    w("private node turbulence_to_flame_speed_ratio {")
    w("    alias output __out:\n        function(5.0)\n            .add_sample(0.0, 3.0)")
    for t in range(5, 50, 5):
        k = 1.5 if t == 5 else 1.75 if t == 10 else 2.0
        w(f"            .add_sample({t}.0, {k} * {t}.0)")
    w("            ;\n}\n")

    w(f"public node {key} {{")
    w("    alias output __out: engine;")
    w("    engine engine(")
    w(f'        name: "{spec["name"]}",')
    w("        starter_torque: 200 * units.lb_ft,\n        starter_speed: 200 * units.rpm,")
    w(f"        redline: {sim_redline} * units.rpm,\n        throttle_gamma: 2.0,")
    w("        fuel: fuel(max_burning_efficiency: 1.0, turbulence_to_flame_speed_ratio: turbulence_to_flame_speed_ratio()),")
    w(f"        hf_gain: 0.01,\n        noise: 1.0,\n        jitter: {0.4 if spec['style'] in ('diesel', 'vintage', 'truck') else 0.25},")
    w(f"        simulation_frequency: {sim_freq}\n    )\n")
    w("    wires wires()\n")
    w(f"    label stroke({stroke} * units.mm)\n    label bore({bore} * units.mm)")
    w(f"    label rod_length({rod} * units.mm)\n    label rod_mass({max(250, 0.9 * disp_cyl_cc):.0f} * units.g)")
    w(f"    label compression_height({max(25, 0.32 * bore):.1f} * units.mm)")
    w(f"    label crank_mass({crank_mass_lb:.1f} * units.lb)\n    label flywheel_mass({fly_mass_lb:.1f} * units.lb)")
    w("    label flywheel_radius(6 * units.inch)")
    w("    label crank_moment(1.5 * disk_moment_of_inertia(mass: crank_mass, radius: stroke))")
    w("    label flywheel_moment(disk_moment_of_inertia(mass: flywheel_mass, radius: flywheel_radius))")
    w("    label other_moment(disk_moment_of_inertia(mass: 1 * units.kg, radius: 1.0 * units.cm))\n")
    w("    crankshaft c0(")
    w("        throw: stroke / 2,\n        flywheel_mass: flywheel_mass,\n        mass: crank_mass,")
    w(f"        friction_torque: {max(0.5, 3.5 * disp_l):.1f} * units.lb_ft,")
    w("        moment_of_inertia: crank_moment + flywheel_moment + other_moment,")
    w(f"        position_x: 0.0,\n        position_y: 0.0,\n        tdc: {90 + ref} * units.deg\n    )\n")
    # Each cylinder gets its own journal placed so it reaches compression TDC
    # at its firing time: TDC = journal - (bank - first bank) (engine-sim).
    for c in range(1, n + 1):
        journal = (fires[c] + bank_of[c] - ref) % 360
        w(f"    rod_journal rj{c}(angle: {journal:.3f} * units.deg)")
    w("    c0")
    for c in range(1, n + 1):
        w(f"        .add_rod_journal(rj{c})")
    w("")
    w("    piston_parameters piston_params(")
    w(f"        mass: {max(150, 0.6 * disp_cyl_cc):.0f} * units.g,\n        compression_height: compression_height,")
    w("        wrist_pin_position: 0.0,\n        displacement: 0.0\n    )")
    w("    connecting_rod_parameters cr_params(\n        mass: rod_mass,")
    w("        moment_of_inertia: rod_moment_of_inertia(mass: rod_mass, length: rod_length),")
    w("        center_of_mass: 0.0,\n        length: rod_length\n    )\n")
    plenum = max(0.25, 0.23 * disp_l)
    if spec.get("itb"):
        plenum = max(0.25, 0.12 * disp_l)
    w("    intake intake(")
    w(f"        plenum_volume: {plenum:.3f} * units.L,")
    w(f"        plenum_cross_section_area: {max(8.0, 3.5 * disp_l):.1f} * units.cm2,")
    w(f"        intake_flow_rate: k_carb({cfm:.1f}),")
    w(f"        runner_flow_rate: k_carb({cfm / n * 1.15:.1f}),")
    w(f"        runner_length: {6.0 if spec.get('itb') else 12.0} * units.inch,")
    w("        idle_flow_rate: k_carb(0.0),")
    w(f"        idle_throttle_plate_position: {style['plate']},")
    w("        velocity_decay: 0.5\n    )\n")
    w("    exhaust_system_parameters es_params(")
    w(f"        outlet_flow_rate: k_carb({cfm * 1.43:.1f}),")
    w(f"        primary_tube_length: {12 + 2 * min(n, 8)} * units.inch,")
    w(f"        primary_flow_rate: k_carb({cfm * 0.71:.1f}),\n        velocity_decay: 1.0\n    )")
    pipes = len(banks)
    lengths = [100, 172] if pipes == 2 else [130]
    if spec["style"] in ("diesel", "truck"):
        lengths = [l * 1.2 for l in lengths]
    for i in range(pipes):
        w(f"    exhaust_system exhaust{i}(es_params, audio_volume: {style['audio']},")
        w(f"        length: {lengths[i]:.0f} * units.inch, impulse_response: ir_lib.{style['ir']})")
    w("")
    w("    cylinder_bank_parameters bank_params(\n        bore: bore,")
    w("        deck_height: stroke / 2 + rod_length + compression_height\n    )")
    for i, angle in enumerate(banks):
        w(f"    cylinder_bank b{i}(bank_params, angle: {angle} * units.deg)")
    for i, angle in enumerate(banks):
        cyls = [c for c in range(1, n + 1) if bank_of[c] == angle]
        w(f"    b{i}")
        for k, c in enumerate(cyls):
            w("        .add_cylinder(")
            w("            piston: piston(piston_params, blowby: k_28inH2O(0.1)),")
            w("            connecting_rod: connecting_rod(cr_params),")
            w(f"            rod_journal: rj{c},\n            intake: intake,")
            w(f"            exhaust_system: exhaust{i},\n            ignition_wire: wires.wire{c},")
            w(f"            sound_attenuation: 1.0,\n            primary_length: {(len(cyls) - k) * 2 + 2} * units.inch\n        )")
        w(f"        .set_cylinder_head(head(intake_camshaft: camshaft.intake{i}, "
          f"exhaust_camshaft: camshaft.exhaust{i}, flip_display: {'true' if i else 'false'}))")
    w("")
    w("    engine")
    for i in range(len(banks)):
        w(f"        .add_cylinder_bank(b{i})")
    w("    engine.add_crankshaft(c0)\n")
    w("    camshafts camshaft()")
    # Camshafts per bank: lobes in each bank's cylinder order, centred on
    # that cylinder's firing time (as in Engine Simulator's own scripts).
    cams = [f"private node camshafts {{"]
    cams.append(f"    input lsa: {style['lsa']} * units.deg;")
    for i in range(len(banks)):
        cams.append(f"    output intake{i}: _intake{i};\n    output exhaust{i}: _exhaust{i};")
    cams.append(f"    label rot360(360 * units.deg)")
    cams.append(f"    camshaft_parameters params(advance: 0 * units.deg, base_radius: 0.75 * units.inch)")
    cams.append("    harmonic_cam_lobe intake_lobe(")
    cams.append(f"        duration_at_50_thou: {style['dur']} * units.deg, gamma: 1.1,")
    cams.append(f"        lift: {style['lift'] * 1000:.0f} * units.thou, steps: 256)")
    cams.append("    harmonic_cam_lobe exhaust_lobe(")
    cams.append(f"        duration_at_50_thou: {style['dur'] + 4} * units.deg, gamma: 1.1,")
    cams.append(f"        lift: {style['lift'] * 1000:.0f} * units.thou, steps: 256)")
    for i, angle in enumerate(banks):
        cams.append(f"    camshaft _intake{i}(params, lobe_profile: intake_lobe)")
        cams.append(f"    camshaft _exhaust{i}(params, lobe_profile: exhaust_lobe)")
        cyls = [c for c in range(1, n + 1) if bank_of[c] == angle]
        cams.append(f"    _exhaust{i}")
        for c in cyls:
            cams.append(f"        .add_lobe(rot360 - lsa + {fires[c]:.3f} * units.deg) // cyl {c}")
        cams.append(f"    _intake{i}")
        for c in cyls:
            cams.append(f"        .add_lobe(rot360 + lsa + {fires[c]:.3f} * units.deg) // cyl {c}")
    cams.append("}\n")
    text = "\n".join(L)
    # camshafts node must be declared before use in the engine node
    text = text.replace(f"public node {key} {{", "\n".join(cams) + f"\npublic node {key} {{", 1)
    tail = []
    tail.append("    function timing_curve(1000 * units.rpm)\n    timing_curve")
    adv = style["adv"]
    for r in range(0, 9):
        rpm = r * 1000 * max(1, sim_redline / 8000)
        deg = 10 + (adv - 10) * min(1.0, rpm / (0.5 * sim_redline))
        tail.append(f"        .add_sample({rpm:.0f} * units.rpm, {deg:.1f} * units.deg)")
    tail.append("    ignition_module ignition_module(timing_curve: timing_curve,")
    tail.append(f"        rev_limit: {sim_redline + 300 * scale} * units.rpm, limiter_duration: 0.1)")
    tail.append("    ignition_module")
    for c in spec["firing"]:
        tail.append(f"        .connect_wire(wires.wire{c}, {fires[c]:.3f} * units.deg)")
    tail.append("    engine.add_ignition_module(ignition_module)\n}\n")
    text += "\n" + "\n".join(tail)
    text += """
private node mtes_vehicle {
    alias output __out:
        vehicle(mass: 1600 * units.kg, drag_coefficient: 0.3,
            cross_sectional_area: (72 * units.inch) * (50 * units.inch),
            diff_ratio: 3.42, tire_radius: 10 * units.inch, rolling_resistance: 200 * units.N);
}
private node mtes_transmission {
    alias output __out:
        transmission(max_clutch_torque: 2000 * units.lb_ft)
        .add_gear(2.97).add_gear(2.07).add_gear(1.43).add_gear(1.00).add_gear(0.71);
}
public node main {
    set_engine(%s())
    set_vehicle(mtes_vehicle())
    set_transmission(mtes_transmission())
}

main()
""" % key
    return text


# Engine Simulator's hand-tuned engines (heads, cams, intake, exhaust
# primaries/collectors and impulse responses: the character heard in its
# demos). A real engine with the same layout and cylinder count starts from
# one of them; its real bore, stroke, redline and name replace the template's.
TEMPLATE_DIR = Path(__file__).resolve().parent / "templates"
TEMPLATES = {
    "single": "01_honda_trx520.mr",
    "i4": "05_honda_vtec.mr",
    "flat4": "02_subaru_ej25_uh.mr",
    "i5": "07_audi_i5.mr",
    "i6": "03_2jz.mr",
    "i6_bmw": "M52B28.mr",
    "v6": "06_even_fire_v6.mr",
    "v8": "07_gm_ls.mr",
    "v8_big": "chev_truck_454.mr",
}


def template_for(key, spec):
    n, layout = spec["cyl"], spec["layout"]
    disp = math.pi / 4 * (spec["bore"] / 10) ** 2 * (spec["stroke"] / 10) * n / 1000
    if n == 1:
        return "single"
    if layout == "I" and n == 4:
        return "i4"
    if layout == "F" and n == 4:
        return "flat4"
    if layout == "I" and n == 5:
        return "i5"
    if layout == "I" and n == 6:
        return "i6_bmw" if key.startswith("bmw_") else "i6"
    if layout == "V" and n == 6:
        return "v6"
    if layout == "V" and n == 8:
        return "v8_big" if disp >= 6.5 else "v8"
    # shortcut: the only V12 template is an 18,000-rpm F1 engine; road V12
    # dimensions make it diverge at speed. Generated V12 until a road V12 exists.
    return None


def generate_from_template(key, spec, gain, template):
    import re
    text = (TEMPLATE_DIR / TEMPLATES[template]).read_text()
    scale = spec.get("rpm_scale", 1)
    redline = spec["redline"] * scale
    bore, stroke = spec["bore"], spec["stroke"]

    def sub(pattern, replacement, count=0, required=True):
        nonlocal text
        text, n = re.subn(pattern, replacement, text, count=count)
        assert n or not required, (key, template, pattern)

    if template == "single":
        sub(r"71\.5 \* units\.mm", f"{stroke} * units.mm")
        sub(r"bore: 96 \* units\.mm", f"bore: {bore} * units.mm")
    elif template == "v8_big":
        sub(r"throw: 2\.0 \* units\.inch", f"throw: {stroke / 2:.3f} * units.mm")
        sub(r"bore: 4\.25 \* units\.inch", f"bore: {bore} * units.mm")
        sub(r"deck_height: 9\.8 \* units\.inch",
            f"deck_height: {stroke / 2:.3f} * units.mm + 7.8 * units.inch")
    elif template == "i6_bmw":
        sub(r"throw: 84 \* units\.mm / 2", f"throw: {stroke} * units.mm / 2")
        sub(r"bore: 84 \* units\.mm", f"bore: {bore} * units.mm")
        sub(r"deck_height: \(210\.0 \+ 1\) \* units\.mm",
            f"deck_height: ({210.0 + (stroke - 84.0) / 2:.2f} + 1) * units.mm")
    else:
        sub(r"label stroke\([^)]*\)", f"label stroke({stroke} * units.mm)", count=1)
        sub(r"label bore\([^)]*\)", f"label bore({bore} * units.mm)", count=1)
    sub(r"redline: [0-9.]+ \* units\.rpm", f"redline: {redline} * units.rpm")
    sub(r"rev_limit: [0-9.]+ \* units\.rpm", f"rev_limit: {redline + 300 * scale} * units.rpm")
    sub(r'name: "[^"]*"', f'name: "{spec["name"]}"', count=1)
    disp = math.pi / 4 * (bore / 10) ** 2 * (stroke / 10) * spec["cyl"] / 1000
    head = []
    if gain is not None:
        head.append(f"// mtes-output-gain: {gain:.3g}")
    if scale != 1:
        head.append(f"// mtes-rpm-scale: {scale}")
    head.append(f"// {spec['name']}: {spec['cyl']} cyl, {disp:.2f} L, bore {bore} x stroke {stroke} mm,")
    head.append(f"// redline {spec['redline']} rpm. Engine Simulator's {TEMPLATES[template]} model")
    head.append("// (its heads, cams, intake and exhaust) with this engine's dimensions.")
    head.append("// Generated by native/profiles/generator/make_engines.py; MIT, see")
    head.append("// generator/templates/ENGINE_SIM_LICENSE.txt.")
    if "public node main" not in text:
        # Engine-only templates (BMW M52, Chevrolet 454): Motor Town drives
        # the crank speed, so a generic car and gearbox only satisfy the simulator.
        engine_node = {"i6_bmw": "M52B28", "v8_big": "chev_truck_454"}[template]
        text += MAIN_FOR_ENGINE_ONLY_TEMPLATE % engine_node
    # Engine Simulator's own main.mr calls main(); a profile must call it itself.
    return "\n".join(head) + "\n" + text.rstrip() + "\n\nmain()\n"


MAIN_FOR_ENGINE_ONLY_TEMPLATE = """
private node mtes_vehicle {
    alias output __out:
        vehicle(mass: 1600 * units.kg, drag_coefficient: 0.3,
            cross_sectional_area: (72 * units.inch) * (50 * units.inch),
            diff_ratio: 3.42, tire_radius: 10 * units.inch, rolling_resistance: 200 * units.N);
}
private node mtes_transmission {
    alias output __out:
        transmission(max_clutch_torque: 2000 * units.lb_ft)
        .add_gear(2.97).add_gear(2.07).add_gear(1.43).add_gear(1.00).add_gear(0.71);
}
public node main {
    set_engine(%s())
    set_vehicle(mtes_vehicle())
    set_transmission(mtes_transmission())
}
"""


def build(key, spec, gain):
    template = template_for(key, spec)
    if template:
        return generate_from_template(key, spec, gain, template)
    return generate(key, spec, gain)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gains", type=Path)
    parser.add_argument("--only", nargs="*")
    args = parser.parse_args()
    gains = json.loads(args.gains.read_text()) if args.gains else {}
    for key, spec in ENGINES.items():
        if args.only and key not in args.only:
            continue
        (OUT / f"es_{key}.mr").write_text(build(key, spec, gains.get(key)))
    write_families()
    print(f"wrote {len(ENGINES) if not args.only else len(args.only)} engines to {OUT}")


def write_families():
    lines = [
        "# Generated by generator/make_engines.py from real_engines.py. First match wins.",
        "# vehicle: Motor Town car (blueprint class, lower case, no underscores) -> the",
        "#          real engine of the real car it is based on.",
        "# asset/cue/maxrpm: engine data of cars not listed (swaps, traffic, new cars).",
        "# Profile '-' keeps the stock sound (electric motors only).",
    ]
    for pattern, name, real, engine in VEHICLES:
        target = "-" if engine == "-" else f"assets/es_{engine}.mr"
        assert engine == "-" or engine in ENGINES, engine
        lines.append(f"# {name}: {real}" + ("" if engine == "-" else f" -> {ENGINES[engine]['name']}"))
        lines.append(f"vehicle\t{pattern}\t{target}")
    for field, pattern, engine in FALLBACK:
        assert engine == "-" or engine in ENGINES, engine
        lines.append(f"{field}\t{pattern}\t{'-' if engine == '-' else f'assets/es_{engine}.mr'}")
    (OUT / "engine_families.tsv").write_text("\n".join(lines) + "\n")


